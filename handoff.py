"""Hand-offs: the agent's finished branch, reviewed with fresh eyes before
matt can fetch it (PLAN-agent-runner.md, Phase 3).

The agent calls hand_off; matt picks a reviewer model on the card and starts
the review. Each review round:
  1. has the runner write a bundle of the branch;
  2. reads that bundle once, records its sha256 and unpacks it into a scratch
     repo here. The reviewers' diff comes from those exact bytes, and
     agent-fetch.sh refuses any other: the agent can rewrite everything under
     /srv/bixagent, its clone and the bundle included;
  3. runs the fresh-eyes-review skill's two reviewers on that diff, with
     prompts read from its SKILL.md and read-only tools.
Every round runs both reviewers: the author is untrusted, so its fixes get the
same staff review as its first attempt.

Review tasks run in this process (ai-router has a single uvicorn worker).
Record changes never await between load and save, so they don't interleave."""
