def test_reviewers_live_reads_stop_where_the_sandboxs_do(env):
    async def base(name, tool_input):
        return "ran"
    run = handoff.ReviewSession("p", Path("/x"), "0" * 40, 1000).executor(base)
    read = lambda path: asyncio.run(run("read_file", {"path": str(path)}))  # noqa: E731
    assert read(env["apps"] / "demo" / "app.py") == "ran"
    assert read(env["apps"] / "demo" / "private" / "notes.md")[1] is True
    assert read(env["tmp"] / "elsewhere")[1] is True
    (env["apps"] / handoff.SANDBOX_UNIT).unlink()
    assert "unreadable" in read(env["apps"] / "demo" / "app.py")[0]


# ── one reviewer ──────────────────────────────────────────────────────────────

def _review(snap, monkeypatch, events, mode="api"):
    async def adapter(*args, **kwargs):
        for ev in events:
            yield ev
    monkeypatch.setattr(handoff, "_stream_claude", adapter)
    monkeypatch.setattr(handoff, "_stream_ollama", adapter)
    rec = {"repo": "demo", "intent": "make x 2"}
    return asyncio.run(handoff._review("staff", rec, snap, mode, "m"))


def test_a_report_is_the_reviewers_last_turn(snap, monkeypatch):
    events = ['event: budget\ndata: {}\n\n', 'event: delta\ndata: {"text": "Reading app.py."}\n\n',
              'event: budget\ndata: {}\n\n', 'event: delta\ndata: {"text": "Ship it."}\n\n',
              'event: done\ndata: {}\n\n']
    assert _review(snap, monkeypatch, events) == "Ship it."


def test_a_reviewer_error_fails_the_review(snap, monkeypatch):
    events = ['event: error\ndata: {"message": "Loop budget exceeded"}\n\n']
    with pytest.raises(handoff.ReviewError, match="Loop budget exceeded"):
        _review(snap, monkeypatch, events)


def test_a_review_too_big_for_a_local_model_is_refused_up_front(snap, monkeypatch):
    monkeypatch.setattr(config, "REVIEW_LOCAL_CONTEXT", 400)
