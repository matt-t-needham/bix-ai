@pytest.mark.parametrize("loaded, ok", [(32768, True), (4096, False), (None, False)])
def test_a_local_report_counts_only_if_ollama_had_the_context(snap, monkeypatch, loaded, ok):
    async def confirm(model):
        if loaded != config.REVIEW_LOCAL_CONTEXT:
            raise handoff.ReviewError(f"Ollama ran {model} with a {loaded} context")
    monkeypatch.setattr(handoff, "_confirm_local_context", confirm)
    events = ['event: delta\ndata: {"text": "fine"}\n\n', 'event: done\ndata: {}\n\n']
    if ok:
        assert _review(snap, monkeypatch, events, mode="local") == "fine"
    else:
        with pytest.raises(handoff.ReviewError, match="context"):
            _review(snap, monkeypatch, events, mode="local")


